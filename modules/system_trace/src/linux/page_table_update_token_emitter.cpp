    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    DD_RESULT PageTableUpdateTokenEmitter::Initialize(DDEventProvider h_provider)
    {
        h_provider_ = h_provider;

        DD_RESULT result = ftrace_.Initialize();

        return result;
    }

    ////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
    void PageTableUpdateTokenEmitter::Cleanup()
    {
        ftrace_.Destroy();
    }

